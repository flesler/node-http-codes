import { writeFileSync } from 'node:fs'
import { STATUS_CODES } from 'node:http'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

function messageToKey(message: string): string {
  return message.replace("'", '').replace(/[- ]/g, '_').toUpperCase()
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src/http-codes.generated.ts')

const entries: string[] = []
for (const code in STATUS_CODES) {
  const message = STATUS_CODES[code]
  if (!message) {
    continue
  }
  const key = messageToKey(message)
  entries.push(`  readonly ${key}: ${Number.parseInt(code, 10)}`)
}

const source = `// Generated by bin/generate-types.ts — do not edit.
// Reflects Node STATUS_CODES at generation time (.nvmrc). Runtime always tracks live Node.

export type HttpCodes = {
${entries.join('\n')}
} & Record<string, number>
`

writeFileSync(out, source)
